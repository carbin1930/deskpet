# One-click BUILD + RUN for this machine (Windows, no VS Build Tools).
#
# Usage:
#   powershell -ExecutionPolicy Bypass -File scripts\dev-local.ps1
#
# What it does:
#   1. Reuse build-local.ps1, which sets up the local GNU toolchain (.tools/ on
#      PATH + rust-lld as linker) and builds a self-contained release exe.
#      This avoids the "dlltool.exe: program not found" error from plain cargo.
#   2. Build incrementally (release deps are cached -> fast) with a retry loop
#      for Defender's transient "os error 5" file locks.
#   3. Launch the exe so you can test the pet (right-click menu, edge docking,
#      layout fix) on your desktop.
#
# To stop: use the tray icon -> Quit, or close this window.
#
# NOTE: keep this file pure ASCII -- PowerShell 5.1 reads UTF-8-without-BOM as
#       GBK and non-ASCII quotes break parsing.

$ErrorActionPreference = "Continue"

$root = Split-Path -Parent $PSScriptRoot
$buildScript = Join-Path $PSScriptRoot "build-local.ps1"
$exe = Join-Path $root "src-tauri/target/release/deskpet.exe"

# Single-threaded cargo avoids concurrent rustc instances fighting over the
# same temporary *.dll_imports.lib generated by dlltool on windows-gnu.
$env:CARGO_BUILD_JOBS = "1"

$built = $false
for ($i = 1; $i -le 6; $i++) {
  Write-Host "=== Build attempt $i ==="
  & $buildScript
  if ($LASTEXITCODE -eq 0) { $built = $true; break }
  Write-Host "Build attempt $i failed; retrying in 1s (Defender may lock a fresh exe)..."
  Start-Sleep -Seconds 1
}
if (-not $built) { throw "Build failed after 6 attempts (see output above)" }
if (-not (Test-Path $exe)) { throw "exe not found after build: $exe" }

Write-Host "=== Launching $exe ==="
& $exe
